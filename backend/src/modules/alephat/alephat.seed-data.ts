const ORDER_NAMES = [
  'ግዕዝ',
  'ካዕብ',
  'ሣልስ',
  'ራብዕ',
  'ኃምስ',
  'ሳድስ',
  'ሳብዕ',
  'ሳምን',
  'ታስዕ',
  'ዐሥር',
  '11ኛ',
  '12ኛ',
  '13ኛ',
  '14ኛ',
  '15ኛ',
];

function makeFamily(
  base: string,
  forms: string[],
  phoneticRoots: string[],
  baseNote: string,
  customOrderNames?: string[],
): SeedFamilyMember[] {
  return forms.map((glyph, idx) => {
    const orderIndex = idx + 1;
    const orderName =
      (customOrderNames && customOrderNames[idx]) || ORDER_NAMES[idx] || `${orderIndex}ኛ`;
    const pron = phoneticRoots[idx] || '';
    return {
      glyph,
      orderIndex,
      orderName,
      pronunciation: pron,
      note: `${glyph}፡ የ${base} ${orderName} ድምጽ። ${baseNote}`,
    };
  });
}

