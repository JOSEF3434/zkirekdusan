/// Network IP Camera streaming RTSP (Real-Time Streaming Protocol).
class NetworkCameraSource extends CameraSource {
  final String rtspUrl;
  final RtspTransport transport;
  final int port;
  final String? username;
  final String? password;

  const NetworkCameraSource({
    this.rtspUrl = '',
    this.transport = RtspTransport.tcp,
    this.port = 554,
    this.username,
    this.password,
    super.audioDeviceId,
  }) : super(
         type: CameraSourceType.networkCamera,
         label: 'IP Camera (RTSP)',
         subtitle: 'PTZ or network camera streaming via RTSP',
         icon: Icons.videocam_outlined,
         requiresLocalHardware: false,
       );

  /// Validates RTSP URL format (must begin with rtsp:// or rtsps://).
  static bool isValidRtspUrl(String url) {
    final trimmed = url.trim();
    if (trimmed.isEmpty) return false;
    final uri = Uri.tryParse(trimmed);
    if (uri == null || uri.host.isEmpty) return false;
    return uri.scheme == 'rtsp' || uri.scheme == 'rtsps';
  }

  /// Returns a redacted copy of [rtspUrl] safe for logs and public badges.
  String get redactedUrl {
    final uri = Uri.tryParse(rtspUrl.trim());
    if (uri == null) return rtspUrl;
    if (uri.userInfo.isNotEmpty) {
      return uri.replace(userInfo: '***:***').toString();
    }
    return uri.toString();
  }

  NetworkCameraSource copyWith({
    String? rtspUrl,
    RtspTransport? transport,
    int? port,
    String? username,
    String? password,
    String? audioDeviceId,
  }) => NetworkCameraSource(
    rtspUrl: rtspUrl ?? this.rtspUrl,
    transport: transport ?? this.transport,
    port: port ?? this.port,
    username: username ?? this.username,
    password: password ?? this.password,
    audioDeviceId: audioDeviceId ?? this.audioDeviceId,
  );
}

/// SRT (Secure Reliable Transport) source.
class SrtEncoderSource extends CameraSource {
  final String host;
  final int port;
  final SrtMode mode;
  final int latencyMs;
  final String? streamId;
  final String? passphrase;

  const SrtEncoderSource({
    this.host = '',
    this.port = 9000,
    this.mode = SrtMode.caller,
    this.latencyMs = 200,
    this.streamId,
    this.passphrase,
    super.audioDeviceId,
  }) : super(
         type: CameraSourceType.srtEncoder,
         label: 'SRT Encoder',
         subtitle: 'Ultra-low latency Secure Reliable Transport',
         icon: Icons.speed_rounded,
         requiresLocalHardware: false,
       );

  /// Validates SRT URL or host.
  static bool isValidSrtUrl(String url) {
    final trimmed = url.trim();
    if (trimmed.isEmpty) return false;
    final uri = Uri.tryParse(trimmed);
    if (uri == null || uri.host.isEmpty) return false;
    return uri.scheme == 'srt';
  }

  String get formattedUri {
    final h = host.trim();
    if (h.isEmpty) return '';
    if (h.startsWith('srt://')) return h;
    final query = <String, String>{
      'mode': mode.name,
      'latency': latencyMs.toString(),
      if (streamId != null && streamId!.trim().isNotEmpty)
        'streamid': streamId!.trim(),
    };
    return Uri(
      scheme: 'srt',
      host: h,
      port: port,
      queryParameters: query,
    ).toString();
  }

  SrtEncoderSource copyWith({
    String? host,
    int? port,
    SrtMode? mode,
    int? latencyMs,
    String? streamId,
    String? passphrase,
    String? audioDeviceId,
  }) => SrtEncoderSource(
    host: host ?? this.host,
    port: port ?? this.port,
    mode: mode ?? this.mode,
    latencyMs: latencyMs ?? this.latencyMs,
    streamId: streamId ?? this.streamId,
    passphrase: passphrase ?? this.passphrase,
    audioDeviceId: audioDeviceId ?? this.audioDeviceId,
  );
}
