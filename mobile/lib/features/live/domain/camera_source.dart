// lib/features/live/domain/camera_source.dart
//
// Camera & Encoder Source domain models for live broadcast capture.
//
// Supports:
// 1. Built-in Camera: Device front/back camera (phone/tablet/webcam).
// 2. Wired Capture Hardware: USB UVC webcam, HDMI capture card, SDI capture card.
// 3. Wireless Camera System: Remote phone camera (WebRTC) or wireless transmitter.
// 4. Screen Share: Device screen or external display capture.
// 5. External Hardware/Software Encoder: ATEM Mini, OBS Studio, vMix, Teradek pushing RTMP directly.
// 6. Network IP Camera: RTSP camera on local LAN or WAN.
// 7. SRT Broadcast Encoder: Secure Reliable Transport (caller/listener).

import 'package:flutter/material.dart';

/// Available camera and video encoder source types for broadcasting.
enum CameraSourceType {
  /// Local device camera (front or back) captured via native camera/WHIP.
  builtIn,

  /// External hardware/software encoder (ATEM Mini, OBS Studio, vMix, Teradek, Yolobox)
  /// pushing RTMP directly to the ingest server. Studio acts as monitor & control desk.
  externalEncoder,

  /// Network/IP camera streaming RTSP over TCP/UDP on local network or public IP.
  networkCamera,

  /// Secure Reliable Transport (SRT) encoder operating in caller or listener mode.
  srtEncoder,

  /// Wired USB Video Class (UVC) camera connected via USB-C / OTG / desktop USB.
  usbUvcCamera,

  /// HDMI camera/switcher captured through a UVC HDMI-to-USB capture device.
  hdmiCapture,

  /// Professional SDI camera captured through an SDI-to-HDMI/USB capture device.
  sdiCapture,

  /// Wireless camera system or paired remote phone camera (WebRTC peer).
  wirelessCamera,

  /// Local device screen capture (MediaProjection / ReplayKit / getDisplayMedia).
  screenShare,
}

/// Transport protocol for RTSP connections.
enum RtspTransport {
  /// TCP interleaved (RFC 2326) — recommended for reliable transmission through firewalls.
  tcp,

  /// UDP unicast — lower latency but subject to packet drop and firewall traversal issues.
  udp,
}

/// Operating mode for SRT connections.
enum SrtMode {
  /// Mobile studio / server acts as caller (connects to remote encoder listener).
  caller,

  /// Mobile studio / server acts as listener (waits for encoder to call in).
  listener,
}

/// Distinguishes the 5 distinct recording targets clearly so audio-only backups
/// are never misrepresented as full video recordings.
enum RecordingTargetMode {
  /// Recording triggered directly onto the connected camera's SD card.
  cameraSdCard,

  /// Synchronized audio + video recorded locally on the phone/browser.
  localDeviceAv,

  /// Local recording handled on an external hardware/software encoder (OBS/ATEM/Yolobox).
  externalEncoder,

  /// Server-side VOD archive generated by the live streaming backend/Cloudinary.
  serverVodArchive,

  /// Microphone audio-only backup saved locally as M4A/AAC.
  localAudioBackup,
}

extension RecordingTargetModeMeta on RecordingTargetMode {
  String get title {
    switch (this) {
      case RecordingTargetMode.cameraSdCard:
        return 'Camera SD Card';
      case RecordingTargetMode.localDeviceAv:
        return 'Phone Audio + Video';
      case RecordingTargetMode.externalEncoder:
        return 'External Encoder Storage';
      case RecordingTargetMode.serverVodArchive:
        return 'Server Broadcast Archive (VOD)';
      case RecordingTargetMode.localAudioBackup:
        return 'Phone Audio-Only Backup (M4A)';
    }
  }

  String get shortBadge {
    switch (this) {
      case RecordingTargetMode.cameraSdCard:
        return 'SD CARD';
      case RecordingTargetMode.localDeviceAv:
        return 'LOCAL AV';
      case RecordingTargetMode.externalEncoder:
        return 'ENCODER';
      case RecordingTargetMode.serverVodArchive:
        return 'SERVER VOD';
      case RecordingTargetMode.localAudioBackup:
        return 'AUDIO ONLY';
    }
  }

  bool get includesVideo => this != RecordingTargetMode.localAudioBackup;
}

/// Abstract representation of any video source configurable in the Live Studio.
abstract class CameraSource {
  final CameraSourceType type;
  final String label;
  final String subtitle;
  final IconData icon;

  /// Whether the phone/browser itself runs local hardware capture (camera/UVC/mic).
  /// False for external encoders/RTSP/SRT/remote peers where media does not come
  /// from this device's built-in camera controller.
  final bool requiresLocalHardware;

  /// Optional preferred audio input ID (from AudioInputOption).
  final String? audioDeviceId;

  const CameraSource({
    required this.type,
    required this.label,
    required this.subtitle,
    required this.icon,
    required this.requiresLocalHardware,
    this.audioDeviceId,
  });
}

/// Built-in mobile device camera or desktop webcam.
class BuiltInCameraSource extends CameraSource {
  final bool isFront;
  final int resolutionWidth;
  final int resolutionHeight;
  final int targetFps;
  final String? deviceId;

  const BuiltInCameraSource({
    this.isFront = true,
    this.resolutionWidth = 1280,
    this.resolutionHeight = 720,
    this.targetFps = 30,
    this.deviceId,
    super.audioDeviceId,
  }) : super(
         type: CameraSourceType.builtIn,
         label: 'Device Camera',
         subtitle: 'Front or rear camera on this device',
         icon: Icons.camera_alt_outlined,
         requiresLocalHardware: true,
       );

  BuiltInCameraSource copyWith({
    bool? isFront,
    int? resolutionWidth,
    int? resolutionHeight,
    int? targetFps,
    String? deviceId,
    String? audioDeviceId,
  }) => BuiltInCameraSource(
    isFront: isFront ?? this.isFront,
    resolutionWidth: resolutionWidth ?? this.resolutionWidth,
    resolutionHeight: resolutionHeight ?? this.resolutionHeight,
    targetFps: targetFps ?? this.targetFps,
    deviceId: deviceId ?? this.deviceId,
    audioDeviceId: audioDeviceId ?? this.audioDeviceId,
  );
}

/// Wired USB UVC, HDMI capture card, or SDI-to-USB capture hardware source.
class WiredCaptureCameraSource extends CameraSource {
  final String deviceId;
  final String deviceName;
  final int resolutionWidth;
  final int resolutionHeight;
  final int targetFps;
  final String videoFormat;
  final bool hasAudio;
  final bool isUvcVerified;

  WiredCaptureCameraSource({
    required super.type,
    required this.deviceId,
    required this.deviceName,
    this.resolutionWidth = 1920,
    this.resolutionHeight = 1080,
    this.targetFps = 30,
    this.videoFormat = 'YUY2 / MJPEG',
    this.hasAudio = true,
    this.isUvcVerified = true,
    super.audioDeviceId,
  }) : assert(
         type == CameraSourceType.usbUvcCamera ||
             type == CameraSourceType.hdmiCapture ||
             type == CameraSourceType.sdiCapture,
       ),
       super(
         label: _labelFor(type, deviceName),
         subtitle: _subtitleFor(type, resolutionWidth, resolutionHeight, targetFps),
         icon: _iconFor(type),
         requiresLocalHardware: true,
       );

  static String _labelFor(CameraSourceType type, String deviceName) {
    if (deviceName.trim().isNotEmpty) return deviceName;
    switch (type) {
      case CameraSourceType.hdmiCapture:
        return 'HDMI Capture Camera';
      case CameraSourceType.sdiCapture:
        return 'SDI Capture Camera';
      default:
        return 'USB / UVC Camera';
    }
  }

  static String _subtitleFor(
    CameraSourceType type,
    int w,
    int h,
    int fps,
  ) {
    final prefix = switch (type) {
      CameraSourceType.hdmiCapture => 'HDMI-to-USB capture',
      CameraSourceType.sdiCapture => 'SDI-to-HDMI/USB capture',
      _ => 'USB UVC capture',
    };
    return '$prefix • ${w}x$h @ ${fps}fps';
  }

  static IconData _iconFor(CameraSourceType type) {
    switch (type) {
      case CameraSourceType.hdmiCapture:
        return Icons.settings_input_hdmi_rounded;
      case CameraSourceType.sdiCapture:
        return Icons.settings_input_component_rounded;
      default:
        return Icons.usb_rounded;
    }
  }

  WiredCaptureCameraSource copyWith({
    CameraSourceType? type,
    String? deviceId,
    String? deviceName,
    int? resolutionWidth,
    int? resolutionHeight,
    int? targetFps,
    String? videoFormat,
    bool? hasAudio,
    bool? isUvcVerified,
    String? audioDeviceId,
  }) => WiredCaptureCameraSource(
    type: type ?? this.type,
    deviceId: deviceId ?? this.deviceId,
    deviceName: deviceName ?? this.deviceName,
    resolutionWidth: resolutionWidth ?? this.resolutionWidth,
    resolutionHeight: resolutionHeight ?? this.resolutionHeight,
    targetFps: targetFps ?? this.targetFps,
    videoFormat: videoFormat ?? this.videoFormat,
    hasAudio: hasAudio ?? this.hasAudio,
    isUvcVerified: isUvcVerified ?? this.isUvcVerified,
    audioDeviceId: audioDeviceId ?? this.audioDeviceId,
  );
}

