  static List<AlephatFamilyMemberModel> _makeFamily(
    String letterId,
    String base,
    List<String> forms,
    List<String> phonetics,
    String baseNote,
  ) {
    return List.generate(forms.length, (idx) {
      final orderIndex = idx + 1;
      final orderName =
          idx < orderNames.length ? orderNames[idx] : '$orderIndexኛ';
      final pron = idx < phonetics.length ? phonetics[idx] : '';
      return AlephatFamilyMemberModel(
        id: '${letterId}_$orderIndex',
        baseLetterId: letterId,
        glyph: forms[idx],
        orderIndex: orderIndex,
        orderName: orderName,
        pronunciation: pron,
        note: '${forms[idx]}፡ የ$base $orderName ድምጽ። $baseNote',
        isPublished: true,
      );
    });
  }

